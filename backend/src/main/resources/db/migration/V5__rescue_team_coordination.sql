-- ---------------------------------------------------------------------
-- Indexes for hot query paths
-- ---------------------------------------------------------------------
CREATE INDEX idx_rescue_vehicles_team  ON rescue_vehicles (team_id);
CREATE INDEX idx_rescue_vehicles_status ON rescue_vehicles (status);
CREATE INDEX idx_rescue_equipment_team ON rescue_equipment (team_id);
CREATE INDEX idx_rescue_equipment_status ON rescue_equipment (status);
CREATE INDEX idx_rescue_missions_team ON rescue_missions (team_id);
CREATE INDEX idx_rescue_missions_disaster ON rescue_missions (disaster_id);
CREATE INDEX idx_rescue_missions_status ON rescue_missions (status);
CREATE INDEX idx_mission_events_mission ON mission_events (mission_id);
CREATE INDEX idx_team_location_team ON team_location_updates (team_id, timestamp);
CREATE INDEX idx_team_shifts_team ON team_shifts (team_id);
CREATE INDEX idx_team_shifts_member ON team_shifts (member_id);
